_CODE_PREFIX = re.compile(r"^(\d{2})\d*$")


def province_code2(admin_code: str | None, name: str | None) -> str | None:
    """`admin_code` 前两位 → 两位代码；没有就按名字回退；再没有返回 None。

    只接受**纯数字**的行政代码：`350000` / `350000.0` 不该出现，但出现了也
    不会把 `"35.0"` 当成代码 —— 前端会拿到 null 并画浅灰。
    """
    code = (admin_code or "").strip()
    match = _CODE_PREFIX.match(code)
    if match is not None:
        return match.group(1)

    label = (name or "").strip()
    if label in PROVINCE_CODES:
        return PROVINCE_CODES[label]
    return PROVINCE_SHORT_CODES.get(label)
